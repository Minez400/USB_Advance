uint64_t NtfsFormatter::generateVolumeSerial() {
    auto now = std::chrono::high_resolution_clock::now().time_since_epoch().count();
    std::mt19937_64 rng(static_cast<uint64_t>(now));
    return rng();
}

void NtfsFormatter::applyUsaFixup(uint8_t* record, uint16_t usa_offset, uint16_t usa_count, uint16_t seq_num) {
    uint16_t* usa = reinterpret_cast<uint16_t*>(record + usa_offset);
    usa[0] = seq_num;

    // Sector 1 end (bytes 510-511)
    uint16_t* sec1_end = reinterpret_cast<uint16_t*>(record + 510);
    usa[1] = *sec1_end;
    *sec1_end = seq_num;

    // Sector 2 end (bytes 1022-1023)
    if (usa_count >= 3) {
        uint16_t* sec2_end = reinterpret_cast<uint16_t*>(record + 1022);
        usa[2] = *sec2_end;
        *sec2_end = seq_num;
    }
}

static std::vector<uint8_t> toUtf16Le(const std::string& str) {
    std::vector<uint8_t> out;
    out.reserve(str.size() * 2);
    for (char c : str) {
        out.push_back(static_cast<uint8_t>(c));
        out.push_back(0);
    }
    return out;
}

static uint64_t getNtfsTimestamp() {
    auto now_epoch = std::chrono::system_clock::now().time_since_epoch();
    int64_t unix_ns = std::chrono::duration_cast<std::chrono::nanoseconds>(now_epoch).count();
    int64_t ntfs_ticks = (unix_ns / 100) + 116444736000000000ULL;
    return static_cast<uint64_t>(ntfs_ticks);
}

static size_t writeResidentAttrHeader(
    uint8_t* dst,
    uint32_t type,
    uint32_t content_size,
    uint16_t attr_id,
    const std::string& attr_name = ""
) {
    auto u16_name = toUtf16Le(attr_name);
    uint8_t name_len = static_cast<uint8_t>(attr_name.size());
    uint16_t name_offset = (name_len > 0) ? 24 : 0;
    uint16_t value_offset = (name_len > 0) ? static_cast<uint16_t>((24 + name_len * 2 + 7) & ~7) : 24;
    uint32_t total_attr_len = (value_offset + content_size + 7) & ~7;

    std::memset(dst, 0, value_offset);
    std::memcpy(dst + 0, &type, 4);
    std::memcpy(dst + 4, &total_attr_len, 4);
    dst[8] = 0; // Resident flag = 0
    dst[9] = name_len;
    std::memcpy(dst + 10, &name_offset, 2);
    uint16_t zero16 = 0;
    std::memcpy(dst + 12, &zero16, 2);
    std::memcpy(dst + 14, &attr_id, 2);
    std::memcpy(dst + 16, &content_size, 4);
    std::memcpy(dst + 20, &value_offset, 2);
    dst[22] = 0;
    dst[23] = 0;

    if (name_len > 0) {
        std::memcpy(dst + name_offset, u16_name.data(), u16_name.size());
    }

    return value_offset;
}

static size_t encodeSingleRunlist(uint8_t* dst, uint64_t length, int64_t lcn) {
    uint8_t len_bytes[8];
    uint8_t len_size = 0;
    uint64_t temp_len = length;
    while (temp_len > 0) {
        len_bytes[len_size++] = static_cast<uint8_t>(temp_len & 0xFF);
        temp_len >>= 8;
    }
    if (len_size == 0) len_bytes[len_size++] = 0;

    uint8_t lcn_bytes[8];
    uint8_t lcn_size = 0;
    int64_t temp_lcn = lcn;
    while (true) {
        uint8_t b = static_cast<uint8_t>(temp_lcn & 0xFF);
        lcn_bytes[lcn_size++] = b;
        temp_lcn >>= 8;
        if ((temp_lcn == 0 && (b & 0x80) == 0) || (temp_lcn == -1 && (b & 0x80) != 0)) break;
        if (lcn_size >= 8) break;
    }

    dst[0] = static_cast<uint8_t>((lcn_size << 4) | (len_size & 0x0F));
    std::memcpy(dst + 1, len_bytes, len_size);
    std::memcpy(dst + 1 + len_size, lcn_bytes, lcn_size);
    dst[1 + len_size + lcn_size] = 0x00;
    return 1 + len_size + lcn_size + 1;
}

static size_t writeNonResidentAttr(
    uint8_t* dst,
    uint32_t type,
    uint64_t num_clusters,
    uint64_t data_size,
    uint32_t cluster_size,
    int64_t start_lcn,
    uint16_t attr_id,
    const std::string& attr_name = ""
) {
    auto u16_name = toUtf16Le(attr_name);
    uint8_t name_len = static_cast<uint8_t>(attr_name.size());
    uint16_t hdr_size = 64; // 0x40
    uint16_t mp_offset = static_cast<uint16_t>(hdr_size + ((name_len * 2 + 7) & ~7));

    size_t rl_size = encodeSingleRunlist(dst + mp_offset, num_clusters, start_lcn);
    uint32_t total_attr_len = static_cast<uint32_t>((mp_offset + rl_size + 7) & ~7);

    std::memset(dst, 0, mp_offset);
    std::memcpy(dst + 0, &type, 4);
    std::memcpy(dst + 4, &total_attr_len, 4);
    dst[8] = 1; // Non-resident flag
    dst[9] = name_len;
    uint16_t name_offset = hdr_size;
    std::memcpy(dst + 10, &name_offset, 2);
    uint16_t zero16 = 0;
    std::memcpy(dst + 12, &zero16, 2);
    std::memcpy(dst + 14, &attr_id, 2);

    uint64_t lowest_vcn = 0;
    uint64_t highest_vcn = num_clusters > 0 ? num_clusters - 1 : 0;
    std::memcpy(dst + 16, &lowest_vcn, 8);
    std::memcpy(dst + 24, &highest_vcn, 8);
    std::memcpy(dst + 32, &mp_offset, 2);

    uint64_t allocated_size = num_clusters * cluster_size;
    std::memcpy(dst + 40, &allocated_size, 8);
    std::memcpy(dst + 48, &data_size, 8);
    std::memcpy(dst + 56, &data_size, 8); // Initialized size

    if (name_len > 0) {
        std::memcpy(dst + name_offset, u16_name.data(), u16_name.size());
    }

    return total_attr_len;
}

void NtfsFormatter::buildBootSector(
    const NativeFormatParams& params,
    uint32_t cluster_size,
    uint64_t mft_cluster,
    uint64_t mftmirr_cluster,
    uint64_t serial,
    std::vector<uint8_t>& out_boot_sector
) {
    out_boot_sector.assign(params.sector_size, 0);
    uint8_t* b = out_boot_sector.data();

    // 0x00: x86 JMP instruction to bootstrap IPL at 0x54
    b[0] = 0xEB;
    b[1] = 0x52;
    b[2] = 0x90;

    // 0x03: OEM ID "NTFS    " (8 bytes)
    std::memcpy(&b[3], "NTFS    ", 8);

    // BIOS Parameter Block (BPB)
    uint16_t bytes_per_sector = static_cast<uint16_t>(params.sector_size);
    std::memcpy(&b[0x0B], &bytes_per_sector, 2);

    uint8_t sectors_per_cluster = static_cast<uint8_t>(cluster_size / params.sector_size);
    b[0x0D] = sectors_per_cluster;

    uint16_t zero16 = 0;
    std::memcpy(&b[0x0E], &zero16, 2);

    b[0x15] = 0xF8; // Media descriptor (fixed disk / mass storage)

    uint16_t spt = 63;
    std::memcpy(&b[0x18], &spt, 2);

    uint16_t heads = 255;
    std::memcpy(&b[0x1A], &heads, 2);

    uint32_t hidden = static_cast<uint32_t>(params.start_lba);
    std::memcpy(&b[0x1C], &hidden, 4);

    b[0x24] = 0x80; // Physical drive number
    b[0x25] = 0x00;
    b[0x26] = 0x80; // Extended boot signature
    b[0x27] = 0x00;

    uint64_t total_sec = params.sector_count - 1; // Reserve backup boot sector
    std::memcpy(&b[0x28], &total_sec, 8);

    std::memcpy(&b[0x30], &mft_cluster, 8);
    std::memcpy(&b[0x38], &mftmirr_cluster, 8);

    b[0x40] = 0xF6; // Clusters per MFT record (-10 => 1024 bytes)
    b[0x41] = 0x00;
    b[0x42] = 0x00;
    b[0x43] = 0x00;

    b[0x44] = 0x01; // Clusters per index buffer (4096 bytes)
    b[0x45] = 0x00;
    b[0x46] = 0x00;
    b[0x47] = 0x00;

    std::memcpy(&b[0x48], &serial, 8);

    static const uint8_t BOOT_CODE[] = {
        0x0e, 0x1f, 0xbe, 0x71, 0x7c, 0xac, 0x22, 0xc0, 0x74, 0x0b, 0x56, 0xb4, 0x0e, 0xbb, 0x07, 0x00,
        0xcd, 0x10, 0x5e, 0xeb, 0xf0, 0x32, 0xe4, 0xcd, 0x16, 0xcd, 0x19, 0xeb, 0xfe,
        'A', ' ', 'd', 'i', 's', 'k', ' ', 'r', 'e', 'a', 'd', ' ', 'e', 'r', 'r', 'o', 'r', ' ',
        'o', 'c', 'c', 'u', 'r', 'r', 'e', 'd', '.', 0x0d, 0x0a, 0x00
    };
    if (params.sector_size >= 0x54 + sizeof(BOOT_CODE)) {
        std::memcpy(b + 0x54, BOOT_CODE, sizeof(BOOT_CODE));
    }

    b[params.sector_size - 2] = 0x55;
    b[params.sector_size - 1] = 0xAA;
}

static void buildCompleteMftRecord(
    uint8_t* record,
    uint32_t record_number,
    const std::string& name,
    uint16_t flags,
    uint32_t cluster_size,
    uint64_t total_clusters,
    const std::string& volume_label
) {
    std::memset(record, 0, 1024);

    std::memcpy(record, "FILE", 4);
    uint16_t usa_offset = 48; // 0x0030
    uint16_t usa_count = 3;
    uint16_t seq_num = 1;
    uint16_t first_attr_offset = 56; // 0x0038
    uint32_t allocated_size = 1024;

    std::memcpy(record + 4, &usa_offset, 2);
    std::memcpy(record + 6, &usa_count, 2);
    std::memcpy(record + 16, &seq_num, 2);
    uint16_t link_count = 1;
    std::memcpy(record + 18, &link_count, 2);
    std::memcpy(record + 20, &first_attr_offset, 2);
    std::memcpy(record + 22, &flags, 2);
    std::memcpy(record + 28, &allocated_size, 4);

    size_t offset = 56;
    uint16_t attr_id = 0;
    uint64_t now_ts = getNtfsTimestamp();

    // 1. $STANDARD_INFORMATION (Type 0x10, 48 bytes)
    {
        uint8_t std_info[48] = {0};
        std::memcpy(&std_info[0], &now_ts, 8);
        std::memcpy(&std_info[8], &now_ts, 8);
        std::memcpy(&std_info[16], &now_ts, 8);
        std::memcpy(&std_info[24], &now_ts, 8);
        uint32_t dos_flags = (flags & 0x0002) ? 0x10 : 0x20;
        std::memcpy(&std_info[32], &dos_flags, 4);

        size_t val_off = writeResidentAttrHeader(record + offset, 0x10, 48, attr_id++);
        std::memcpy(record + offset + val_off, std_info, 48);
        offset = (offset + val_off + 48 + 7) & ~7;
    }

    // 2. $FILE_NAME (Type 0x30)
    if (!name.empty()) {
        auto u16_name = toUtf16Le(name);
        uint8_t name_len = static_cast<uint8_t>(name.size());
        uint32_t fn_size = 66 + (name_len * 2);
        std::vector<uint8_t> fn_content(fn_size, 0);

        uint64_t parent_ref = 5;
        std::memcpy(&fn_content[0], &parent_ref, 8);
        std::memcpy(&fn_content[8], &now_ts, 8);
        std::memcpy(&fn_content[16], &now_ts, 8);
        std::memcpy(&fn_content[24], &now_ts, 8);
        std::memcpy(&fn_content[32], &now_ts, 8);
        uint32_t dos_flags = (flags & 0x0002) ? 0x10 : 0x20;
        std::memcpy(&fn_content[56], &dos_flags, 4);
        fn_content[64] = name_len;
        fn_content[65] = (name == "$MFT" || name == "$LogFile" || name == "$Volume" || name == "$Bitmap" || name == "$Boot" || name == "$UpCase") ? 0 : 3;
        std::memcpy(&fn_content[66], u16_name.data(), u16_name.size());

        size_t val_off = writeResidentAttrHeader(record + offset, 0x30, fn_size, attr_id++);
        std::memcpy(record + offset + val_off, fn_content.data(), fn_size);
        offset = (offset + val_off + fn_size + 7) & ~7;
    }

    switch (record_number) {
        case 0: // $MFT
        {
            offset += writeNonResidentAttr(
                record + offset,
                0x80, // $DATA
                8,    // 8 clusters = 32 KB
                32768,
                cluster_size,
                4,    // Start LCN = 4
                attr_id++
            );

            // Resident $BITMAP (0xB0): 32 records allocated = 4 bytes (0xFF, 0xFF, 0xFF, 0xFF)
            uint8_t mft_bitmap[8] = { 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00 };
            size_t val_off = writeResidentAttrHeader(record + offset, 0xB0, 8, attr_id++);
            std::memcpy(record + offset + val_off, mft_bitmap, 8);
            offset = (offset + val_off + 8 + 7) & ~7;
            break;
        }

        case 1: // $MFTMirr
        {
            offset += writeNonResidentAttr(
                record + offset,
                0x80,
                1,
                4096,
                cluster_size,
                12,
                attr_id++
            );
            break;
        }

        case 2: // $LogFile
        {
            offset += writeNonResidentAttr(
                record + offset,
                0x80,
                512,
                2097152,
                cluster_size,
                16,
                attr_id++
            );
            break;
        }

        case 3: // $Volume
        {
            std::string label = volume_label.empty() ? "USB ADVANCE" : volume_label;
            auto u16_label = toUtf16Le(label);
            size_t val_off = writeResidentAttrHeader(record + offset, 0x60, static_cast<uint32_t>(u16_label.size()), attr_id++);
            std::memcpy(record + offset + val_off, u16_label.data(), u16_label.size());
            offset = (offset + val_off + u16_label.size() + 7) & ~7;

            uint8_t vol_info[12] = {0};
            vol_info[8] = 3; // NTFS 3.1
            vol_info[9] = 1;
            vol_info[10] = 0;
            val_off = writeResidentAttrHeader(record + offset, 0x70, 12, attr_id++);
            std::memcpy(record + offset + val_off, vol_info, 12);
            offset = (offset + val_off + 12 + 7) & ~7;
            break;
        }

        case 4: // $AttrDef
        {
            offset += writeNonResidentAttr(
                record + offset,
                0x80,
                1,
                2560,
                cluster_size,
                13,
                attr_id++
            );
            break;
        }

        case 5: // . (Root directory)
        {
            uint8_t idx_root[48] = {0};
            uint32_t indexed_attr = 0x30;
            uint32_t collation = 1;
            uint32_t idx_block_size = 4096;
            uint8_t clusters_per_block = 1;

            std::memcpy(&idx_root[0], &indexed_attr, 4);
            std::memcpy(&idx_root[4], &collation, 4);
            std::memcpy(&idx_root[8], &idx_block_size, 4);
            idx_root[12] = clusters_per_block;

            uint32_t first_entry_offset = 16;
            uint32_t total_entry_size = 32;
            uint32_t allocated_entry_size = 32;
            std::memcpy(&idx_root[16], &first_entry_offset, 4);
            std::memcpy(&idx_root[20], &total_entry_size, 4);
            std::memcpy(&idx_root[24], &allocated_entry_size, 4);

            // Index entry starts at offset 32 (16 bytes header + 16 offset):
            // Bytes 32..39: FileReference (uint64_t = 0 for end-marker entry)
            uint64_t zero_fileref = 0;
            std::memcpy(&idx_root[32], &zero_fileref, 8);

            // Byte 40..41: Entry length (uint16_t = 16)
            uint16_t entry_length = 16;
            std::memcpy(&idx_root[40], &entry_length, 2);

            // Byte 42..43: Key length (uint16_t = 0)
            uint16_t key_length = 0;
            std::memcpy(&idx_root[42], &key_length, 2);

            // Byte 44..45: Entry flags (uint16_t = 0x02: INDEX_ENTRY_END)
            uint16_t entry_flags = 0x02;
            std::memcpy(&idx_root[44], &entry_flags, 2);

            size_t val_off = writeResidentAttrHeader(record + offset, 0x90, 48, attr_id++, "$I30");
            std::memcpy(record + offset + val_off, idx_root, 48);
            offset = (offset + val_off + 48 + 7) & ~7;
            break;
        }

        case 6: // $Bitmap
        {
            uint64_t bitmap_bytes = (total_clusters + 7) / 8;
            uint64_t bitmap_clusters = (bitmap_bytes + cluster_size - 1) / cluster_size;
            offset += writeNonResidentAttr(
                record + offset,
                0x80,
                bitmap_clusters,
                bitmap_bytes,
                cluster_size,
                560,
                attr_id++
            );
            break;
        }

        case 7: // $Boot
        {
            offset += writeNonResidentAttr(
                record + offset,
                0x80,
                2,
                8192,
                cluster_size,
                0,
                attr_id++
            );
            break;
        }

        case 8: // $BadClust
        {
            size_t val_off = writeResidentAttrHeader(record + offset, 0x80, 0, attr_id++, "$Bad");
            offset = (offset + val_off + 7) & ~7;
            break;
        }

        case 9: // $Secure
        {
            size_t val_off = writeResidentAttrHeader(record + offset, 0x80, 0, attr_id++, "$SDS");
            offset = (offset + val_off + 7) & ~7;
            break;
        }

        case 10: // $UpCase
        {
            offset += writeNonResidentAttr(
                record + offset,
                0x80,
                32,
                131072,
                cluster_size,
                528,
                attr_id++
            );
            break;
        }

        case 11: // $Extend
        {
            uint8_t idx_root[48] = {0};
            uint32_t indexed_attr = 0x30;
            uint32_t collation = 1;
            uint32_t idx_block_size = 4096;
            std::memcpy(&idx_root[0], &indexed_attr, 4);
            std::memcpy(&idx_root[4], &collation, 4);
            std::memcpy(&idx_root[8], &idx_block_size, 4);
            idx_root[12] = 1;
            uint32_t first_entry_offset = 16;
            uint32_t total_entry_size = 32;
            uint32_t allocated_entry_size = 32;
            std::memcpy(&idx_root[16], &first_entry_offset, 4);
            std::memcpy(&idx_root[20], &total_entry_size, 4);
            std::memcpy(&idx_root[24], &allocated_entry_size, 4);
            uint16_t entry_length = 16;
            uint16_t entry_flags = 0x02; // INDEX_ENTRY_END
            std::memcpy(&idx_root[32], &entry_length, 2);
            std::memcpy(&idx_root[36], &entry_flags, 2);

            size_t val_off = writeResidentAttrHeader(record + offset, 0x90, 48, attr_id++, "$I30");
            std::memcpy(record + offset + val_off, idx_root, 48);
            offset = (offset + val_off + 48 + 7) & ~7;
            break;
        }

        default:
            break;
    }

    uint32_t end_marker = 0xFFFFFFFF;
    std::memcpy(record + offset, &end_marker, 4);
    offset += 8;

    uint32_t real_size = static_cast<uint32_t>(offset);
    std::memcpy(record + 24, &real_size, 4);

    NtfsFormatter::applyUsaFixup(record, usa_offset, usa_count, seq_num);
}

bool NtfsFormatter::format(
    const NativeFormatParams& params,
    WriteSectorsFn write_fn,
    ProgressFn progress_fn
) {
    if (params.sector_count < 4096) {
        return false; // Partition must be at least 2 MB
    }

    uint32_t cluster_size = params.cluster_size_bytes > 0
        ? params.cluster_size_bytes
        : calculateOptimalClusterSize(params.sector_count * params.sector_size);

    uint32_t sectors_per_cluster = cluster_size / params.sector_size;
    uint64_t total_clusters = params.sector_count / sectors_per_cluster;

    progress_fn(5.0f, "Calculating canonical NTFS 3.1 geometry and structures...");

    uint64_t mft_cluster = 4;
    uint64_t mftmirr_cluster = 12;
    uint64_t serial = generateVolumeSerial();

    // 1. Build and write Volume Boot Record (and clean cluster 0) at LBA 0
    progress_fn(12.0f, "Writing NTFS Volume Boot Record (LBA 0)...");
    std::vector<uint8_t> boot_sector;
    buildBootSector(params, cluster_size, mft_cluster, mftmirr_cluster, serial, boot_sector);

    // Prepare full boot cluster (cluster 0) with VBR at sector 0 and zeroed trailing sectors
    std::vector<uint8_t> boot_cluster(cluster_size, 0);
    std::memcpy(boot_cluster.data(), boot_sector.data(), params.sector_size);

    if (!write_fn(params.start_lba, sectors_per_cluster, boot_cluster.data())) {
        return false;
    }

    // Write Backup Boot Record to the last sector of partition
    progress_fn(20.0f, "Writing NTFS Backup Boot Record...");
    uint64_t backup_lba = params.start_lba + params.sector_count - 1;
    if (!write_fn(backup_lba, 1, boot_sector.data())) {
        return false;
    }

    // 2. Initialize and write Master File Table (MFT, 32 records of 1024 bytes = 32 KB)
    progress_fn(32.0f, "Generating Master File Table ($MFT)...");
    std::vector<uint8_t> mft_buffer(32 * 1024, 0);

    buildCompleteMftRecord(&mft_buffer[0 * 1024], 0, "$MFT", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[1 * 1024], 1, "$MFTMirr", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[2 * 1024], 2, "$LogFile", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[3 * 1024], 3, "$Volume", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[4 * 1024], 4, "$AttrDef", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[5 * 1024], 5, ".", 3, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[6 * 1024], 6, "$Bitmap", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[7 * 1024], 7, "$Boot", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[8 * 1024], 8, "$BadClust", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[9 * 1024], 9, "$Secure", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[10 * 1024], 10, "$UpCase", 1, cluster_size, total_clusters, params.volume_label);
    buildCompleteMftRecord(&mft_buffer[11 * 1024], 11, "$Extend", 3, cluster_size, total_clusters, params.volume_label);

    // Reserved records 12 to 31
    for (uint32_t r = 12; r < 32; ++r) {
        buildCompleteMftRecord(&mft_buffer[r * 1024], r, "", 0, cluster_size, total_clusters, params.volume_label);
    }

    // Write Primary $MFT (32 KB = 8 clusters starting at cluster 4)
    uint64_t mft_lba = params.start_lba + (mft_cluster * sectors_per_cluster);
    uint32_t mft_sectors = static_cast<uint32_t>(mft_buffer.size() / params.sector_size);
    if (!write_fn(mft_lba, mft_sectors, mft_buffer.data())) {
        return false;
    }

    // Write $MFTMirr (Mirror of records 0..3: 4 KB = 1 cluster at cluster 12)
    progress_fn(48.0f, "Writing $MFTMirr mirror records...");
    uint64_t mftmirr_lba = params.start_lba + (mftmirr_cluster * sectors_per_cluster);
    if (!write_fn(mftmirr_lba, sectors_per_cluster, mft_buffer.data())) {
        return false;
    }

    // 3. Write $AttrDef (cluster 13)
    progress_fn(55.0f, "Writing $AttrDef schema definitions...");
    std::vector<uint8_t> attrdef_cluster(cluster_size, 0);
    std::memcpy(attrdef_cluster.data(), ATTRDEF_NTFS3X, sizeof(ATTRDEF_NTFS3X));
    uint64_t attrdef_lba = params.start_lba + (13 * sectors_per_cluster);
    if (!write_fn(attrdef_lba, sectors_per_cluster, attrdef_cluster.data())) {
        return false;
    }

    // 4. Initialize $LogFile (clusters 16..527 = 2 MB prefilled with 0xFF)
    progress_fn(65.0f, "Pre-allocating $LogFile transaction journal (2 MB)...");
    std::vector<uint8_t> logfile_chunk(64 * 1024, 0xFF); // 64 KB batches
    uint32_t logfile_chunk_sectors = static_cast<uint32_t>(logfile_chunk.size() / params.sector_size);
    uint64_t logfile_start_lba = params.start_lba + (16 * sectors_per_cluster);
    uint64_t logfile_total_sectors = 512 * sectors_per_cluster;
    uint64_t written_sectors = 0;
    while (written_sectors < logfile_total_sectors) {
        uint32_t to_write = static_cast<uint32_t>(std::min<uint64_t>(logfile_chunk_sectors, logfile_total_sectors - written_sectors));
        if (!write_fn(logfile_start_lba + written_sectors, to_write, logfile_chunk.data())) {
            return false;
        }
        written_sectors += to_write;
    }

    // 5. Generate and write $UpCase table (clusters 528..559 = 128 KB)
    progress_fn(80.0f, "Generating Unicode $UpCase table (128 KB)...");
    std::vector<uint8_t> upcase_buffer(128 * 1024, 0);
    buildUpcaseTable(reinterpret_cast<uint16_t*>(upcase_buffer.data()));

    uint64_t upcase_lba = params.start_lba + (528 * sectors_per_cluster);
    uint32_t upcase_sectors = static_cast<uint32_t>(upcase_buffer.size() / params.sector_size);
    if (!write_fn(upcase_lba, upcase_sectors, upcase_buffer.data())) {
        return false;
    }

    // 6. Write $Bitmap (cluster 560)
    progress_fn(92.0f, "Generating volume cluster bitmap ($Bitmap)...");
    uint64_t bitmap_bytes = (total_clusters + 7) / 8;
    uint64_t bitmap_clusters = (bitmap_bytes + cluster_size - 1) / cluster_size;
    uint64_t bitmap_alloc_bytes = bitmap_clusters * cluster_size;
    std::vector<uint8_t> bitmap(bitmap_alloc_bytes, 0);

    // Mark system allocated clusters as in use (bit = 1)
    uint64_t system_allocated_clusters = 560 + bitmap_clusters;
    for (uint64_t c = 0; c < system_allocated_clusters && c < total_clusters; ++c) {
        bitmap[c / 8] |= (1 << (c % 8));
    }

    uint64_t bitmap_lba = params.start_lba + (560 * sectors_per_cluster);
    uint32_t bitmap_sectors = static_cast<uint32_t>(bitmap_alloc_bytes / params.sector_size);
    if (!write_fn(bitmap_lba, bitmap_sectors, bitmap.data())) {
        return false;
    }

    progress_fn(98.0f, "Finalizing NTFS structures and flushing buffers...");
    return true;
}

